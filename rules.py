def normalize(value: str) -> str:
    return " ".join(value.casefold().replace("ـ", "").split())


def search_rules(query: str, category: str = "all") -> list[dict]:
    """Return rules ordered by simple Arabic-friendly keyword overlap."""
    wanted_category = normalize(category)
    terms = set(normalize(query).replace("؟", " ").replace("،", " ").split())
    matches = []
    for rule in RULES:
        if wanted_category != "all" and normalize(rule["category"]) != wanted_category:
            continue
        searchable = normalize(" ".join([
            rule["id"], rule["category"], rule["title"], rule["summary"],
            rule["example"], *rule["keywords"],
        ]))
        score = sum(1 for term in terms if term in searchable)
        if score or not terms:
            matches.append((score, rule))
    matches.sort(key=lambda item: item[0], reverse=True)
    source_names = {
        "arabicacademy.gov.eg": "مجمع اللغة العربية بالقاهرة",
        "library.ksaa.gov.sa": "مجمع الملك سلمان العالمي للغة العربية",
        "moh.gov.sa": "وزارة الصحة السعودية",
        "stats.gov.sa": "الهيئة العامة للإحصاء السعودية",
        "awkafonline.gov.eg": "وزارة الأوقاف المصرية",
    }
    results = []
    for _, rule in matches[:8]:
        result = dict(rule)
        result["source_name"] = next(
            (name for domain, name in source_names.items() if domain in rule["source"]),
            "مصدر موثق",
        )
        results.append(result)
    return results
